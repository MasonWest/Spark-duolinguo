def main():
    apply = "--apply" in sys.argv
    conn = sqlite3.connect(DB)
    cur = conn.cursor()

    print("=== 三段文案重写 ===")
    changed = 0
    for lid, fields in sorted(NARR.items()):
        cur.execute("select order_index, title, content from lessons where id=?", (lid,))
        row = cur.fetchone()
        if not row:
            print(f"  !! lesson {lid} 不存在")
            continue
        oi, title, raw = row
        d = json.loads(raw)
        stats = []
        for k in ("review", "problem", "preview"):
            old = d.get(k) or ""
            new = fields[k]
            stats.append(f"{k} {len(old)}->{len(new)}")
            d[k] = new
        if apply:
            cur.execute("update lessons set content=? where id=?",
                        (json.dumps(d, ensure_ascii=False), lid))
        changed += 1
        print(f"  [{lid}] {title}: " + " | ".join(stats))

    print(f"\n共 {changed} 课")

    print("\n=== key_points 重复词清理 ===")
    fixed = 0
    for lid in NARR:
        cur.execute("select content from lessons where id=?", (lid,))
        d = json.loads(cur.fetchone()[0])
        kps = d.get("key_points") or []
        hit = False
        for i, kp in enumerate(kps):
            if not isinstance(kp, str):
                continue
            new = kp
            for old, rep in KP_FIXES:
                if old in new:
                    new = new.replace(old, rep)
            if new != kp:
                kps[i] = new
                hit = True
                fixed += 1
                print(f"  [{lid}] {kp[:40]}... -> 去重")
        if hit and apply:
            cur.execute("update lessons set content=? where id=?",
                        (json.dumps(d, ensure_ascii=False), lid))
    if fixed == 0:
        print("  无重复词命中")

    if apply:
        conn.commit()
        print("\n已提交写入。")
    else:
        print("\n[DRY-RUN] 未写入。加 --apply 生效。")
    conn.close()


if __name__ == "__main__":
    main()
